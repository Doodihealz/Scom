			return Default;
		}
		return value;
	}

	internal static string BuildLuaRuleTable()
	{
		StringBuilder stringBuilder = new StringBuilder("local SCO_VETERANCY_RULES = {\n");
		foreach (KeyValuePair<string, VeterancyRule> item in Overrides.OrderBy<KeyValuePair<string, VeterancyRule>, string>((KeyValuePair<string, VeterancyRule> pair) => pair.Key, StringComparer.Ordinal))
		{
			stringBuilder.Append("    [\"").Append(item.Key).Append("\"] = { kills = {")
				.Append(string.Join(", ", item.Value.Kills))
				.Append("}, regen = {")
				.Append(string.Join(", ", item.Value.Regen.Select(FormatNumber)))
				.Append("} },\n");
		}
		stringBuilder.Append("}\n").Append("local SCO_VETERANCY_DEFAULT = { kills = { 25, 100, 250, 500, 1000 }, regen = { 2, 4, 6, 8, 10 } }\n").Append("local function SCO_GetVeterancyRule(tpId)\n")
			.Append("    return SCO_VETERANCY_RULES[tpId] or SCO_VETERANCY_DEFAULT\n")
			.Append("end\n");
		return stringBuilder.ToString();
	}

	private static VeterancyRule Rule(string kills, string regen)
	{
		return new VeterancyRule((from value in kills.Split(new char[1] { '/' })
			select int.Parse(value, CultureInfo.InvariantCulture)).ToArray(), (from value in regen.Split(new char[1] { '/' })
			select float.Parse(value, CultureInfo.InvariantCulture)).ToArray());
	}

	private static string FormatNumber(float value)
	{
		return value.ToString("0.###", CultureInfo.InvariantCulture);
	}
